"""
Writes extension/model.js: everything the extension needs to run with no server.

    python export_extension_model.py

Text: the interpretable Dreaddit model (TF-IDF + linguistic features + Logistic Regression)
trained on the whole dataset. Typing: Logistic Regression on SWELL-KW bursts. VADER's word
lists come from NLTK, so they cannot drift from the Python version. tests/test_engine_parity.py
checks that extension/engine.js gives the same answers as Python.
"""

from __future__ import annotations

import json

import nltk.data
from nltk.sentiment.vader import VaderConstants
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

import config
import run_burst_model
import train_demo
from dataio import loaders
from features import burst_features, text_features

TYPING_WEIGHT = 0.25    # bursts carry little signal across people (Decision Log D31)
UNCLEAR_BELOW = 0.5     # a typing estimate less sure than this is shown as unclear
PATH = config.PROJECT_ROOT / "extension" / "model.js"


def vader_tables() -> dict:
    c = VaderConstants()
    lexicon = {}
    for line in nltk.data.load("sentiment/vader_lexicon.zip/vader_lexicon/vader_lexicon.txt").split("\n"):
        word, measure = line.strip().split("\t")[0:2]
        lexicon[word] = float(measure)
    return {"lexicon": lexicon, "negate": sorted(c.NEGATE), "booster": c.BOOSTER_DICT,
            "idioms": c.SPECIAL_CASE_IDIOMS, "punc": c.PUNC_LIST}


def text_tables(pipe, ling: list[str]) -> dict:
    pre, clf = pipe.named_steps["pre"], pipe.named_steps["clf"]
    tfidf, scaler = pre.named_transformers_["tfidf"], pre.named_transformers_["ling"]
    names = tfidf.get_feature_names_out().tolist()
    coef = clf.coef_[0].tolist()
    return {"classes": [str(c) for c in clf.classes_], "intercept": float(clf.intercept_[0]),
            "terms": {t: [float(i), float(w)] for t, i, w in zip(names, tfidf.idf_, coef[:len(names)])},
            "stop": sorted(ENGLISH_STOP_WORDS),
            "ling": {"names": ling, "mean": scaler.mean_.tolist(), "scale": scaler.scale_.tolist(), "coef": coef[len(names):]},
            "words": {"negative": sorted(text_features.NEGATIVE_WORDS), "stress": sorted(text_features.STRESS_WORDS),
                      "positive": sorted(text_features.POSITIVE_WORDS), "negation": sorted(text_features.NEGATION_WORDS),
                      "first": sorted(text_features.FIRST_PERSON)}}


def typing_tables(pipe) -> dict:
    return {"classes": [str(c) for c in pipe.classes_], "features": burst_features.FEATURES,
            "median": pipe.named_steps["i"].statistics_.tolist(), "mean": pipe.named_steps["s"].mean_.tolist(),
            "scale": pipe.named_steps["s"].scale_.tolist(), "coef": pipe.named_steps["m"].coef_.tolist(),
            "intercept": pipe.named_steps["m"].intercept_.tolist()}


def fit_models():
    dd = loaders.load_dreaddit()
    text, ling = train_demo.train_text(dd["text"], dd["stress_label"], [])
    b = run_burst_model.swell_bursts()
    typing = run_burst_model.model().fit(b[burst_features.FEATURES], b["label"])
    return text, ling, typing


def main() -> None:
    text, ling, typing = fit_models()
    tables = {"typingWeight": TYPING_WEIGHT, "unclearBelow": UNCLEAR_BELOW, "minWords": 3, "minKeys": burst_features.MIN_BURST_KEYS,
              "vader": vader_tables(), "text": text_tables(text, ling), "typing": typing_tables(typing)}
    PATH.write_text("// Generated by export_extension_model.py. Do not edit.\nglobalThis.STRESS_MODEL = "
                    + json.dumps(tables, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print(f"{PATH} {PATH.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
